"""AST -> IR.

One walk, in source order, producing a command list. Evaluation and emission
stay interleaved because the language requires it: a `for` body emits once per
item with different bindings, and `const app = executable(...) { ... }` is
simultaneously an emission and a binding. What changed is the output — IR nodes
rather than text, so anything that has to look at what was produced can look at
it instead of predicting it.

`const`, `for`, `if` and `record` are transpile-time and produce no IR; `set`,
`when`, `function` and the target vocabulary do.
"""

from __future__ import annotations

from typing import Any

from . import ir
from . import nodes as N
from .astutil import find_setting
from .commands import CommandsMixin, minimum_command
from .errors import ScmakeError
from .expressions import ExpressionsMixin
from .records import RecordsMixin, RecordType
from .targets import TargetCtx, TargetsMixin
from .values import truthy


class Analyzer(ExpressionsMixin, RecordsMixin, TargetsMixin, CommandsMixin):
    def __init__(self, filename: str = "build.scmake"):
        self.filename = filename
        self.nodes: list = []
        self.scopes: list[dict[str, Any]] = [{}]
        self.fetch_included = False
        self.needs_gtest = False
        self.has_gtest_include = False
        self.has_enable_testing = False
        self.header_slot = 0
        # Set by emit_statement for every top-level statement; read by
        # emit_target when it is the first one to declare a target.
        self.statement_slot = 0
        self.first_target_slot: int | None = None
        self.minimum_emitted = False
        self.functions: set[str] = set()
        self.records: dict[str, RecordType] = {}
        # Targets declared without sources, by name; cleared when sources or a
        # file set arrive later. Whatever is left at the end is an error.
        self.sourceless: dict[str, Any] = {}

    # --- entry point ------------------------------------------------------

    def run(self, program: list) -> list:
        self.nodes.append(ir.Comment(
            [f"Generated by SmartCMake from {self.filename} — do not edit."]))
        self.nodes.append(ir.Blank())
        # cmake_minimum_required must be the first command in the file, whatever
        # order the source puts things in, so it is hoisted out of the project.
        for st in program:
            if isinstance(st, N.Project):
                minimum = find_setting(st.body, "cmakeMinimum")
                if minimum is not None:
                    self.nodes.append(minimum_command(self.eval(minimum)))
                    self.minimum_emitted = True
                break
        self.header_slot = len(self.nodes)
        for st in program:
            self.emit_statement(st, self.nodes)
        if self.sourceless:
            name, st = next(iter(self.sourceless.items()))
            raise self.err(f"target {name!r} has no sources", st)
        self._insert_auto_includes()
        return self.nodes

    def _insert_auto_includes(self) -> None:
        auto = []
        if self.needs_gtest:
            if not self.has_enable_testing:
                auto.append(ir.Command("enable_testing"))
            if not self.has_gtest_include:
                auto.append(ir.Command("include", ["GoogleTest"]))
        if not auto:
            return
        slot = self.first_target_slot
        if slot is None:
            slot = self.header_slot
        self.nodes[slot:slot] = [ir.Blank(), *auto]

    # --- scopes -----------------------------------------------------------

    def push(self) -> None:
        self.scopes.append({})

    def pop(self) -> None:
        self.scopes.pop()

    def define(self, name: str, value: Any) -> None:
        self.scopes[-1][name] = value

    def lookup(self, name: str):
        for scope in reversed(self.scopes):
            if name in scope:
                return scope[name], True
        return None, False

    def err(self, msg: str, node) -> ScmakeError:
        return ScmakeError(msg, getattr(node, "line", 0), 0, self.filename)

    # --- statement dispatch -----------------------------------------------

    def emit_statement(self, st, out: list, ctx: TargetCtx | None = None) -> None:
        if isinstance(st, N.CommentBlock):
            out.append(ir.Blank())
            out.append(ir.Comment(st.lines))
            out.append(ir.Blank())
            return

        mark = len(out)
        # Where this statement's block begins, comment lines included. A target
        # claims it as the anchor for the auto-inserted enable_testing() /
        # include(GoogleTest), which is why the auto-includes land above the
        # comment rather than between it and the command it describes.
        #
        # The analyzer reports the position instead of it being predicted from
        # the AST: a predicate over statement shapes only recognises the ones
        # that visibly hold a target, so it has to be extended in step with the
        # emitter and silently misplaces the preamble when it is not.
        if out is self.nodes:
            self.statement_slot = mark
        if st.comments:
            out.append(ir.Blank())
            out.append(ir.Comment(st.comments))
        after_comments = len(out)

        self.dispatch(st, out, ctx)

        # A comment on a transpile-time statement documents the .scmake, not the
        # CMake; if the statement emitted nothing, the comment goes with it.
        if st.comments and len(out) == after_comments:
            del out[mark:]

    def dispatch(self, st, out: list, ctx: TargetCtx | None) -> None:
        if isinstance(st, N.Project):
            self.emit_project(st, out)
        elif isinstance(st, N.ConstDecl):
            self.declare_const(st, out)
        elif isinstance(st, N.RecordDecl):
            self.declare_record(st)
        elif isinstance(st, N.SetVar):
            self.emit_set(st, out)
        elif isinstance(st, N.ForOf):
            self.emit_for(st, out, ctx)
        elif isinstance(st, N.If):
            self.emit_if(st, out, ctx)
        elif isinstance(st, N.When):
            self.emit_when(st, out, ctx)
        elif isinstance(st, N.Target):
            self.emit_target(st, out)
        elif isinstance(st, N.MethodCall):
            self.emit_method_call(st, out)
        elif isinstance(st, N.Reopen):
            self.emit_reopen(st, out)
        elif isinstance(st, N.Fetch):
            self.emit_fetch(st, out)
        elif isinstance(st, N.Function):
            self.emit_function(st, out)
        elif isinstance(st, N.Install):
            self.emit_install(st, out, ctx)
        elif isinstance(st, N.Raw):
            out.append(ir.Raw(str(self.eval(st.value)).splitlines() or [""]))
        elif isinstance(st, N.Setting):
            self.emit_setting(st, out, ctx)
        elif isinstance(st, N.Call):
            self.emit_call(st, out, ctx)
        else:  # pragma: no cover - every node type is handled above
            raise self.err(f"unsupported statement {type(st).__name__}", st)

    # --- transpile-time constructs ----------------------------------------

    def declare_const(self, st: N.ConstDecl, out: list) -> None:
        # A target on the right-hand side is declared here and bound as a
        # handle; every other value is an ordinary transpile-time binding.
        if isinstance(st.value, N.Target):
            if st.type_ref is not None:
                raise self.err("a target declaration cannot be annotated — "
                               "its type is the kind of target it declares", st)
            # The comment block sits on the const, but it documents the target;
            # hand it over so emit_target does not space it away.
            st.value.comments = st.comments
            self.define(st.name, self.emit_target(st.value, out))
            return
        value = self.eval(st.value)
        if st.type_ref is not None:
            # Up front: check_type only reaches the name through the elements,
            # so `const X: Suit[] = []` would never resolve it.
            self.check_type_exists(st.type_ref, st)
            value = self.check_type(value, st.type_ref, st, st.name)
        self.define(st.name, value)

    def emit_for(self, st: N.ForOf, out: list, ctx: TargetCtx | None) -> None:
        items = self.eval(st.iterable)
        if not isinstance(items, list):
            raise self.err("for (... of ...) needs a list", st)
        for item in items:
            self.push()
            self.define(st.var, item)
            for sub in st.body:
                self.emit_statement(sub, out, ctx)
            self.pop()

    def emit_if(self, st: N.If, out: list, ctx: TargetCtx | None) -> None:
        branch = st.then if truthy(self.eval(st.cond)) else st.orelse
        self.push()
        for sub in branch:
            self.emit_statement(sub, out, ctx)
        self.pop()

    # --- configure-time branch --------------------------------------------

    def emit_when(self, st: N.When, out: list, ctx: TargetCtx | None) -> None:
        opening = f"if({self.condition(st.cond)})"
        # Both branches are walked in source order, because walking has side
        # effects that the output depends on: `include(FetchContent)` is emitted
        # by the first fetch anywhere, and a function is registered where it is
        # declared. Building the else arm first would move both.
        body = self._branch(st.then, ctx)
        # An `else` the branch left empty still has to be written, so absence
        # (None) and emptiness ([]) are kept apart here.
        orelse = self._branch(st.orelse, ctx) if st.orelse else None
        out.append(ir.Block(opening, body, "endif()", orelse))

    def _branch(self, body: list, ctx: TargetCtx | None) -> list:
        out: list = []
        self.push()
        for sub in body:
            self.emit_statement(sub, out, ctx)
        self.pop()
        return out


def analyze(program: list, filename: str = "build.scmake") -> list:
    return Analyzer(filename).run(program)
